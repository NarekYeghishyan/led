"""Copy the static design (Design/site, built by Design/site-src/build_shop.py) into the Next.js app.

Run from the repo root:  python web/scripts/import_design.py
Writes:
  web/src/styles/site.css        every <style> block of Design/site/category.html, in page order (shared CSS: tokens,
                                 header, catalog popup, footer, cards, hover effects, responsive rules, category page)
  web/src/components/icon-symbols.ts  the icon sprite (<symbol>s) as a string, rendered once by the layout
  web/public/img/                logo.png + placeholder/*.svg (default product images)
Re-run after changing the templates' shared CSS. Pages that already live in web/ are edited there, not in the templates.
"""
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "Design" / "site"
WEB = ROOT / "web"

html = (SITE / "category.html").read_text(encoding="utf-8")

# 1. CSS: all <style> blocks in order (head + the shared blocks build_shop.py appends at the end)
blocks = re.findall(r"<style[^>]*>(.*?)</style>", html, re.S)
css = "\n\n".join(b.strip() for b in blocks)
# the templates load images from /img/... — same path in web/public/img
header = ("/* GENERATED by web/scripts/import_design.py from Design/site/category.html — do not edit by hand.\n"
          "   Site-specific overrides go in src/styles/app.css. */\n")
(WEB / "src" / "styles").mkdir(parents=True, exist_ok=True)
(WEB / "src" / "styles" / "site.css").write_text(header + css + "\n", encoding="utf-8")

# 1b. product page CSS: <style> blocks of product.html that category.html doesn't have (the PDP block)
pblocks = re.findall(r"<style[^>]*>(.*?)</style>", (SITE / "product.html").read_text(encoding="utf-8"), re.S)
have = {b.strip() for b in blocks}
pcss = "\n\n".join(b.strip() for b in pblocks if b.strip() not in have and ".pdp{" in b)
assert pcss, "product page CSS block not found"
(WEB / "src" / "styles" / "product.css").write_text(header.replace("category.html", "product.html") + pcss + "\n", encoding="utf-8")

# 1c. shop pages CSS (cart / favourites / compare / checkout / brand: .sp-*, .br-*): cart.html's block that category.html lacks
cart_html = (SITE / "cart.html").read_text(encoding="utf-8")
sblocks = [b.strip() for b in re.findall(r"<style[^>]*>(.*?)</style>", cart_html, re.S) if b.strip() not in have and ".sp-" in b]
assert sblocks, "shop pages CSS block not found"
(WEB / "src" / "styles" / "shop.css").write_text(header.replace("category.html", "cart.html") + "\n\n".join(sblocks) + "\n", encoding="utf-8")
html += "".join(re.findall(r'<symbol id="sp-[^"]+".*?</symbol>', cart_html, re.S))  # sp-* icons join the sprite below

# 2. icon sprite: every <symbol> on the page (main sprite after <body> + the info pages' ix-* icons), first one per id wins
seen, parts = set(), []
for sm in re.finditer(r'<symbol id="([^"]+)".*?</symbol>', html, re.S):
    if sm.group(1) not in seen:
        seen.add(sm.group(1))
        parts.append(re.sub(r"\s*\n\s*", "", sm.group(0)))
symbols = "".join(parts)
for need in ("tower", "laptop", "cpu", "monitor", "head", "wifi", "cart", "heart", "ix-box", "ix-wallet", "ix-ref"):
    assert need in seen, f"icon {need} missing from the sprite"
ts = ("// GENERATED by web/scripts/import_design.py from Design/site/category.html — do not edit by hand.\n"
      "// Icons are used as <svg className=\"i\"><use href=\"#name\"/></svg>.\n"
      f"export const SPRITE = {symbols!r};\n")
# python repr gives a JS-compatible single-quoted string as long as there are no odd escapes
(WEB / "src" / "components" / "icon-symbols.ts").write_text(ts, encoding="utf-8")

# 3. images
img = WEB / "public" / "img"
(img / "placeholder").mkdir(parents=True, exist_ok=True)
shutil.copy2(SITE / "img" / "logo.png", img / "logo.png")
for f in (SITE / "img" / "placeholder").glob("*.svg"):
    shutil.copy2(f, img / "placeholder" / f.name)

print(f"site.css {len(css) // 1024} KB from {len(blocks)} blocks, {symbols.count('<symbol')} icons, images copied")
